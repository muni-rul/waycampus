export interface Programme {
  id: string;
  name: string;
  code?: string;
  level: 'UG' | 'PG' | 'RESEARCH' | 'DIPLOMA';
  departmentName: string;
  departmentCategory?: 'AIDED' | 'SELF_FINANCING' | 'BOTH';
  complementarySubjects?: string[];
  searchAliases?: string[];
}

export interface ClassroomRecord {
  id: string;
  name: string; // e.g. "PG-BOTANY-First year"
  department: string;
  year: string; // "First year", "Second year", "Third year"
  level: 'UG' | 'PG';
  category?: 'AIDED' | 'SELF_FINANCING';
  roomNumber: string; // Official classroom identifier: "SM153", "MG244", etc.
  building: string | null;
  floor: number | string | null;
  panoramaId: string | null;
  nodeId: string | null;
  locationVerified: boolean;
  searchAliases?: string[];
}

export interface LaboratoryRecord {
  id: string;
  name: string; // e.g. "UG - BSc Physics Lab (Core & Complementary) - Aided"
  department: string;
  category?: 'AIDED' | 'SELF_FINANCING' | 'BOTH' | 'RESEARCH' | 'FACILITY';
  building: string | null;
  floor: number | string | null;
  panoramaId: string | null;
  nodeId: string | null;
  locationVerified: boolean;
  searchAliases?: string[];
}

